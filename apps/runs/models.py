from django.db import models
from django.utils import timezone

from apps.evaluations.models import Evaluation
from apps.prompts.models import PromptPopulation


class EvaluationRun(models.Model):
    class Status(models.TextChoices):
        PENDING = "pending", "Pending"
        RUNNING = "running", "Running"
        COMPLETED = "completed", "Completed"
        FAILED = "failed", "Failed"

    evaluation = models.ForeignKey(
        Evaluation, related_name="runs", on_delete=models.CASCADE
    )
    prompt_population = models.ForeignKey(
        PromptPopulation, related_name="runs", on_delete=models.CASCADE
    )
    status = models.CharField(
        max_length=32, choices=Status.choices, default=Status.PENDING
    )
    total_prompts = models.PositiveIntegerField(default=0)
    completed_prompts = models.PositiveIntegerField(default=0)
    total_generations = models.PositiveIntegerField(default=0)
    completed_generations = models.PositiveIntegerField(default=0)
    started_at = models.DateTimeField(null=True, blank=True)
    finished_at = models.DateTimeField(null=True, blank=True)
    error_message = models.TextField(blank=True, default="")
    # True when responses are POSTed by an external bot instead of being
    # generated by an in-process worker thread.
    external = models.BooleanField(default=False)
    # Last sign of progress (generation finished / responses POSTed).
    heartbeat_at = models.DateTimeField(null=True, blank=True)
    # Target LLM settings this run was executed with (never the API key). The
    # evaluation keeps only ONE LLMConfig, so this is what makes past runs of
    # a reused flow comparable.
    llm_snapshot = models.JSONField(default=dict, blank=True)
    # Free-text name shown in the run history (e.g. the flow node title).
    label = models.CharField(max_length=200, blank=True, default="")

    class Meta:
        ordering = ["-id"]

    def __str__(self):
        return f"EvaluationRun #{self.id}"

    def save(self, *args, **kwargs):
        if self._state.adding and self.heartbeat_at is None:
            self.heartbeat_at = timezone.now()
        super().save(*args, **kwargs)
